  /**
   * waifu-web: 资产是否**全部**就绪（模型 / 动作 / 贴图 / 着色器）。
   *
   * 不要退回只看 `_initialized`：它在"动作加载完"就置位，而贴图（setupTextures）与
   * 着色器（loadShaders）是在那之后才开始加载的。只看它的话，上层会在贴图绑定、
   * 着色器编译完成前就认为可以渲染——表现为画布先出现、贴图后补上，或首帧空白。
   *
   * 完整就绪要三个条件同时成立：
   *   1) `_initialized`：模型 / 动作 / 表情 / 物理等资产已解析；
   *   2) `_state == LoadStep.CompleteSetup`：全部贴图已绑定——`update()` 与 `draw()`
   *      也以此为门槛，不到这个状态模型既不更新也不绘制；
   *   3) 着色器已加载：drawMesh 在 `_isShaderLoaded == false` 时直接 return，画不出东西。
   *
   * 模型没有贴图时不会有 onLoad 回调（`_state` 会停在 WaitLoadTexture），这里放行。
   * 兜底：贴图若因 404 / CORS 失败，onLoad 永不触发，严格等待会一直卡到上层超时——
   * 超过 TextureWaitLimitMs 就放行，让模型带着缺失的贴图先显示，而不是整块消失。
   */
  public isReady(): boolean {
    if (!this._initialized) {
      return false;
    }
    const textureCount = this._modelSetting
      ? this._modelSetting.getTextureCount()
      : 0;
    if (textureCount > 0 && this._state != LoadStep.CompleteSetup) {
      const waited =
        this._textureWaitStart > 0 ? Date.now() - this._textureWaitStart : 0;
      if (waited < LAppModel.TextureWaitLimitMs) {
        return false;
      }
      if (!this._textureWaitWarned) {
        this._textureWaitWarned = true;
        CubismLogInfo(
          'waifu-web: 贴图等待超时，先以已就绪的部分显示模型'
        );
      }
    }
    return this._isShaderReady();
  }

  /**
   * waifu-web: 着色器是否已加载完成。
   * 着色器管理器按 GL 上下文缓存单例，`getShader(gl)` 取不到说明该上下文尚未注册。
   * 探测本身出错时不阻断加载——宁可早一点显示，也不要因为探测失败把模型卡死。
   */
  private _isShaderReady(): boolean {
    try {
      const gl = this._subdelegate
        ? this._subdelegate.getGlManager().getGl()
        : null;
      if (!gl) {
        return true;
      }
      const shader = CubismShaderManager_WebGL.getInstance().getShader(gl);
      return !!(shader && shader._isShaderLoaded);
    } catch {
      return true;
    }
  }

  /**
   * waifu-web: 是否已确定加载失败。
   * 只有"结构文件取不到"与"模型主体取不到"这两种情况会置位——它们之后
   * 不可能再进入 CompleteSetup，上层据此立即失败，不必等满超时。
   * 表情/动作/物理等可选资源缺失不在此列（官方本来就容忍）。
   */
  public isFailed(): boolean {
    return this._loadFailed;
  }

  /**
   * waifu-web: 当前动作是否正在自己驱动眼睛（含 EyeBlink 组参数的曲线）。
   * 动画核心用它决定眨眼要不要让位——动作自己在动眼睛时，核心这帧不写眼睛参数，
   * 否则会把动作写的闭眼（例如打瞌睡）顶回"睁开"。
   */
  public isMotionDrivingEyes(): boolean {
    if (this._eyeBlinkHoldHandle === -1) return false;
    return !this._motionManager.isFinishedByHandle(this._eyeBlinkHoldHandle);
  }

  /**
   * モデルを描画する処理。モデルを描画する空間のView-Projection行列を渡す。
   */
  public doDraw(): void {
    if (this._model == null) return;

    // キャンバスサイズを渡す
    const canvas = this._subdelegate.getCanvas();
    const viewport: number[] = [0, 0, canvas.width, canvas.height];

    this.getRenderer().setRenderState(
      this._subdelegate.getFrameBuffer(),
      viewport
    );
    this.getRenderer().drawModel(LAppDefine.ShaderPath);
  }

  /**
   * モデルを描画する処理。モデルを描画する空間のView-Projection行列を渡す。
   */
  public draw(matrix: CubismMatrix44): void {
    if (this._model == null) {
      return;
    }

    // 各読み込み終了後
    if (this._state == LoadStep.CompleteSetup) {
      matrix.multiplyByMatrix(this._modelMatrix);

      this.getRenderer().setMvpMatrix(matrix);

      this.doDraw();
    }
  }

  public async hasMocConsistencyFromFile() {
    CSM_ASSERT(this._modelSetting.getModelFileName().localeCompare(``));

    // CubismModel
    if (this._modelSetting.getModelFileName() != '') {
      const modelFileName = this._modelSetting.getModelFileName();

      const response = await fetch(this._assetUrl(modelFileName));
      const arrayBuffer = await response.arrayBuffer();

      this._consistency = CubismMoc.hasMocConsistency(arrayBuffer);

      if (!this._consistency) {
        CubismLogInfo('Inconsistent MOC3.');
      } else {
        CubismLogInfo('Consistent MOC3.');
      }

      return this._consistency;
    } else {
      LAppPal.printMessage('Model data does not exist.');
    }
  }

